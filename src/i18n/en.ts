// `en` is declared `as const` so every string keeps its literal type. That's
// wrong for a shared dictionary shape: it would force uk.ts (and any other
// locale) to contain the exact same English text instead of its own
// translations. DeepString walks the inferred shape and widens every leaf
// string back to `string`, while still requiring the same keys/nesting/arrays.
type DeepString<T> = T extends string
	? string
	: T extends readonly (infer U)[]
		? readonly DeepString<U>[]
		: T extends object
			? { [K in keyof T]: DeepString<T[K]> }
			: T;

export type Dictionary = DeepString<typeof en>;
